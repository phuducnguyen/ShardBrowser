// Builds src/app/styles/herov.generated.css from the design system in
// docs/design-system/ (the source of truth).
//
// The prototypes style bare class names (.btn, .card, .group, .label …) at the
// top level. The launcher still has pages built from Tailwind utilities, and a
// few of those names collide (.group for one). So every selector is prefixed
// with `.hv`, and a window opts in by rendering inside <div class="hv">.
// Keyframes are renamed hv-* for the same reason. Run: npm run build:herov-css
import { readFileSync, writeFileSync } from "node:fs";
import postcss from "postcss";

const DIR = new URL("../docs/design-system/", import.meta.url);
const OUT = new URL("../src/app/styles/herov.generated.css", import.meta.url);
const SCOPE = ".hv";
const DARK = ':root[data-theme="dark"]';

/** Returns the scoped selector, or null when the rule belongs to the page, not a window. */
function scopeSelector(raw) {
  const s = raw.trim();
  if (s === ":root") return SCOPE;
  if (s === DARK) return `${DARK} ${SCOPE}`;
  if (s === "body") return SCOPE;
  if (s === "html" || s === "*" || s === ".app") return null;
  // `:root:not([data-theme="dark"]) .x` keeps the page-level condition in front of the scope.
  const rooted = s.match(/^(:root(?::not\([^)]*\)|\[[^\]]*\])*)\s+(.+)$/);
  if (rooted) return `${rooted[1]} ${SCOPE} ${rooted[2]}`;
  return `${SCOPE} ${s}`;
}

export function build() {
  const root = postcss.parse(
    ["tokens.css", "components.css"].map((f) => readFileSync(new URL(f, DIR), "utf8")).join("\n"),
  );

  const frames = new Set();
  root.walkAtRules("keyframes", (a) => frames.add(a.params));
  const names = [...frames].sort((a, b) => b.length - a.length).map((n) => n.replace(/[-/\\^$*+?.()|[\]{}]/g, "\\$&"));
  const frameRe = new RegExp(`(?<![\\w-])(${names.join("|")})(?![\\w-])`, "g");

  root.walkAtRules("keyframes", (a) => { a.params = `hv-${a.params}`; });
  root.walkDecls(/^animation(-name)?$/, (d) => { d.value = d.value.replace(frameRe, "hv-$1"); });
  root.walkDecls("--font", (d) => { d.value = d.value.replace('"Figtree"', '"Figtree Variable", "Figtree"'); });

  root.walkRules((rule) => {
    if (rule.parent?.type === "atrule" && rule.parent.name === "keyframes") return;
    // The prototype's page-wide minimum width must not become a minimum width for every `.hv` block (the rail is one).
    if (rule.selectors.some((s) => s.trim() === "body")) rule.walkDecls("min-width", (d) => d.remove());
    const out = rule.selectors.map(scopeSelector).filter(Boolean);
    if (rule.selectors.some((s) => s.trim() === "html") || out.length === 0) { rule.remove(); return; }
    rule.selectors = out;
  });
  // Drop @media blocks emptied by the pass above.
  root.walkAtRules((a) => { if (a.nodes && a.nodes.length === 0) a.remove(); });

  const header = "/* GENERATED by scripts/build-herov-css.mjs from docs/design-system/ — do not edit. */\n";
  const adapt = `
/* Adaptation to the app shell (not part of the prototype CSS). */
.hv .main { height: 100%; }
.hv > .rail { height: 100%; }
.hv .topbar, .hv .view { flex: none; }
.hv .view { flex: 1; }
`;
  return header + root.toString().trim() + "\n" + adapt;
}

if (import.meta.url === `file:///${process.argv[1].replace(/\\/g, "/")}`) {
  writeFileSync(OUT, build());
  console.log("wrote src/app/styles/herov.generated.css");
}
